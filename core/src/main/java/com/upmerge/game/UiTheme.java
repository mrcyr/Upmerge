    static UiTheme fromIndex(int index) {
        int safe = Math.floorMod(index, NAMES.length);
        return new UiTheme(safe);
    }

    int cubeColor(long value) {
        if (value >= 2 && (value & (value - 1L)) == 0L) {
            int power = Long.numberOfTrailingZeros(value);
            if (power >= 1 && power <= 10) return cubes[power - 1];
            float hue = (power * .105f) % 1f;
            int red = Math.round((.45f + .45f * hue) * 255f);
            int green = Math.round((.80f - .20f * hue) * 255f);
            int blue = Math.round(.95f * 255f);
            return (red << 16) | (green << 8) | blue;
        }
        return 0xf5f5ff;
    }

    static int mix(int a, int b, float amount) {
        float t = Math.max(0f, Math.min(1f, amount));
        int r = Math.round(((a >>> 16) & 255) * (1f-t) + ((b >>> 16) & 255) * t);
        int g = Math.round(((a >>> 8) & 255) * (1f-t) + ((b >>> 8) & 255) * t);
        int bl = Math.round((a & 255) * (1f-t) + (b & 255) * t);
        return (r << 16) | (g << 8) | bl;
    }
